package fr.thegamerfarmer.jype;

import com.sun.tools.javac.code.Flags;
import com.sun.tools.javac.tree.JCTree;
import com.sun.tools.javac.tree.TreeMaker;
import com.sun.tools.javac.tree.TreeScanner;
import com.sun.tools.javac.util.Names;

import java.util.*;

/**
 * Records {@code new ALIAS(...)} and {@code ALIAS::new} before Enter, then prepares consumers.
 *
 * <p>An alias is a type variable after transformation, so Java cannot instantiate it. Each
 * creation is later rewritten by {@link ConstructionFactories} into a call to the runtime
 * factory of the type system that compiled it. Factories hold one binding per loaded holder
 * class: the most specific type system that overrides the alias installs its concrete class,
 * as with Jype's shared static storage.
 *
 * <p>Creations are keyed by compilation unit and source position, because later passes may copy
 * a tree (for example static initializers) while keeping its position. Consumers whose type
 * system overrides an alias with an existing ancestor factory receive a static initializer in
 * each top-level class; it loads the generated installer before any code of that class runs.
 */
final class ManagedConstruction {
    /** Prefix of generated factory holders, {@code <system>.Jype$New$<ALIAS>}. */
    static final String HOLDER_PREFIX = "Jype$New$";
    /** Simple name of the generated consumer installer, {@code <system>.Jype$Install}. */
    static final String INSTALLER = "Jype$Install";

    /**
     * One source creation.
     *
     * @param scope type system compiling the creation
     * @param alias instantiated managed name
     * @param arity explicit argument count, or {@code -1} for a constructor reference
     * @param staticInitializer whether no class or method type variable is in scope
     * @param error diagnostic reported by the processor for an unsupported form, or {@code null}
     * @param sitePackage package of the creating class, for constructor access checks
     * @param site qualified name of the creating top-level class, for private constructors
     */
    record Creation(String scope, String alias, int arity, boolean staticInitializer, String error,
                    String sitePackage, String site) {}

    private final Map<JCTree.JCCompilationUnit, Map<Integer, Creation>> creations = new IdentityHashMap<>();
    private final Set<String> installers = new LinkedHashSet<>();
    private final Set<String> sourceSystems = new LinkedHashSet<>();

    ManagedConstruction() {}

    /** Whether a class is generated by this feature and must not be treated as user source. */
    static boolean isGenerated(CharSequence simpleName) {
        String name = simpleName.toString();
        return name.startsWith(HOLDER_PREFIX) || name.equals(INSTALLER);
    }

    static String holderName(String scope, String alias) {
        return scope + "." + HOLDER_PREFIX + alias;
    }

    /** Creations of a compilation unit, by source position. */
    Map<Integer, Creation> creations(JCTree.JCCompilationUnit unit) {
        return creations.getOrDefault(unit, Map.of());
    }

    Map<JCTree.JCCompilationUnit, Map<Integer, Creation>> allCreations() {
        return creations;
    }

    /** Type systems declared by a source {@code package-info.java}; only they may own generated classes. */
    Set<String> sourceSystems() {
        return sourceSystems;
    }

    /** Type systems that receive a generated installer. */
    Set<String> installers() {
        return installers;
    }

    /** Whether this compilation instantiates an alias of the given system. */
    boolean createsIn(String scope, String alias) {
        return creations.values().stream().flatMap(map -> map.values().stream())
                .anyMatch(creation -> creation.error() == null
                        && creation.scope().equals(scope) && creation.alias().equals(alias));
    }

    /** Scans a root class before any Jype transformation; method and class parameters shadow aliases. */
    void collect(JCTree.JCCompilationUnit unit, JCTree.JCClassDecl root, String scope, Set<String> managed) {
        if (managed.isEmpty()) return;
        String pkg = unit.getPackageName() == null ? "" : unit.getPackageName().toString();
        String site = pkg.isEmpty() ? root.name.toString() : pkg + "." + root.name;
        new Scanner(unit, scope, managed, false, false, pkg, site).scan(root);
    }

    /**
     * Lexical walk of one alias scope.
     *
     * <p>Member classes keep parameters named after aliases as managed positions, like root classes;
     * local and anonymous classes shadow them. Static field initializers and static blocks have no
     * class or method type variable, so their creations are typed by the erased binding.
     */
    private final class Scanner extends TreeScanner {
        private final JCTree.JCCompilationUnit unit;
        private final String scope;
        private final Set<String> visible;
        private final boolean inBody;
        private final boolean staticInitializer;
        private final String pkg;
        private final String site;

        Scanner(JCTree.JCCompilationUnit unit, String scope, Set<String> visible, boolean inBody,
                boolean staticInitializer, String pkg, String site) {
            this.unit = unit;
            this.scope = scope;
            this.visible = visible;
            this.inBody = inBody;
            this.staticInitializer = staticInitializer;
            this.pkg = pkg;
            this.site = site;
        }

        private Scanner nested(Set<String> names, boolean body, boolean initializer) {
            return new Scanner(unit, scope, names, body, initializer, pkg, site);
        }

        @Override public void visitClassDef(JCTree.JCClassDecl tree) {
            Set<String> local = new HashSet<>(visible);
            if (inBody) tree.typarams.forEach(parameter -> local.remove(parameter.name.toString()));
            // An anonymous class in a static initializer still has no enclosing class variable.
            nested(local, false, inBody && staticInitializer).scan(tree.defs);
        }

        @Override public void visitMethodDef(JCTree.JCMethodDecl tree) {
            Set<String> local = new HashSet<>(visible);
            tree.typarams.forEach(parameter -> local.remove(parameter.name.toString()));
            // Static methods receive method-owned alias parameters; only initializer contexts lack them.
            Scanner body = nested(local, true, staticInitializer);
            body.scan(tree.params);
            body.scan(tree.body);
            body.scan(tree.defaultValue);
        }

        @Override public void visitVarDef(JCTree.JCVariableDecl tree) {
            boolean staticField = !inBody && (tree.mods.flags & Flags.STATIC) != 0;
            nested(visible, true, staticInitializer || staticField).scan(tree.init);
        }

        @Override public void visitBlock(JCTree.JCBlock tree) {
            boolean staticBlock = !inBody && (tree.flags & Flags.STATIC) != 0;
            nested(visible, true, staticInitializer || staticBlock).scan(tree.stats);
        }

        @Override public void visitNewClass(JCTree.JCNewClass tree) {
            if (tree.clazz instanceof JCTree.JCIdent identifier && visible.contains(identifier.name.toString())) {
                String alias = identifier.name.toString();
                String error = tree.def != null
                        ? "[Jype] Anonymous subclasses of managed type " + alias
                        + " are not supported; declare a named class and bind it in the type system."
                        : tree.encl != null ? "[Jype] Qualified creation of managed type " + alias + " is not supported."
                        : !tree.typeargs.isEmpty()
                        ? "[Jype] Constructor type arguments are not supported for managed type " + alias + "."
                        : null;
                record(unit, tree.pos, new Creation(scope, alias, tree.args.size(), staticInitializer, error, pkg, site));
                scan(tree.args);
                if (tree.def != null) scan(tree.def);
                return;
            }
            super.visitNewClass(tree);
        }

        @Override public void visitReference(JCTree.JCMemberReference tree) {
            if (tree.getMode() == com.sun.source.tree.MemberReferenceTree.ReferenceMode.NEW
                    && tree.expr instanceof JCTree.JCIdent identifier
                    && visible.contains(identifier.name.toString())) {
                record(unit, tree.pos, new Creation(scope, identifier.name.toString(), -1, staticInitializer, null,
                        pkg, site));
                return;
            }
            super.visitReference(tree);
        }
    }

    private void record(JCTree.JCCompilationUnit unit, int pos, Creation creation) {
        creations.computeIfAbsent(unit, ignored -> new HashMap<>()).put(pos, creation);
    }

    /**
     * Makes each top-level class of a consumer load its installer first.
     *
     * @param scope consumer type system
     * @param roots top-level classes governed by it in this compilation
     */
    void injectInstaller(String scope, Collection<JCTree.JCClassDecl> roots, TreeMaker make, Names names) {
        installers.add(scope);
        for (JCTree.JCClassDecl cls : roots) {
            if ((cls.mods.flags & (Flags.INTERFACE | Flags.ANNOTATION)) != 0) continue;
            make.at(cls.pos);
            JCTree.JCStatement call = make.Exec(make.Apply(com.sun.tools.javac.util.List.nil(),
                    make.Select(PreEnterTrees.buildQualifiedName(scope + "." + INSTALLER, make, names),
                            names.fromString("run")), com.sun.tools.javac.util.List.nil()));
            JCTree.JCBlock block = make.Block(Flags.STATIC, com.sun.tools.javac.util.List.of(call));
            // Enum constants must remain the first members of an enum body.
            int index = 0;
            if ((cls.mods.flags & Flags.ENUM) != 0) {
                while (index < cls.defs.size() && cls.defs.get(index) instanceof JCTree.JCVariableDecl constant
                        && (constant.mods.flags & Flags.ENUM) != 0) index++;
            }
            List<JCTree> defs = new ArrayList<>(cls.defs);
            defs.add(index, block);
            cls.defs = com.sun.tools.javac.util.List.from(defs);
        }
    }
}
